#!/usr/bin/env python3
"""Generate the built-in colour scheme from a seed colour using matugen.

Development-time tool; at runtime the shell only needs matugen for
wallpaper-derived schemes. Writes two files:

  core/ColorScheme.qml  fallback dark/light role maps (seed below)
  core/ThemeColors.qml  typed colour roles bound to a role map

    tools/gen-palette.py "#5E8C7A"
"""
import json
import os
import re
import subprocess
import sys
import tempfile

# Material 3 roles exposed by the theme.
ROLES = [
    "primary", "on_primary", "primary_container", "on_primary_container",
    "secondary", "on_secondary", "secondary_container", "on_secondary_container",
    "tertiary", "on_tertiary", "tertiary_container", "on_tertiary_container",
    "error", "on_error", "error_container", "on_error_container",
    "background", "on_background",
    "surface", "on_surface", "surface_variant", "on_surface_variant",
    "surface_dim", "surface_bright",
    "surface_container_lowest", "surface_container_low", "surface_container",
    "surface_container_high", "surface_container_highest",
    "outline", "outline_variant",
    "inverse_surface", "inverse_on_surface", "inverse_primary",
    "shadow", "scrim",
]

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def camel(name):
    # QML reserves "on" + capital for signal handlers, so Material's "onX"
    # roles are exposed as "contentX" (e.g. onPrimary -> contentPrimary).
    name = re.sub(r"(^|_)on_", r"\1content_", name)
    return re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)


def matugen(seed, scheme):
    with tempfile.TemporaryDirectory() as tmp:
        # An empty config keeps matugen from reading the user's own templates.
        cfg = os.path.join(tmp, "matugen.toml")
        with open(cfg, "w") as f:
            f.write("[config]\n\n[templates]\n")
        out = subprocess.run(
            ["matugen", "color", "hex", seed, "--dry-run", "-q", "--json", "hex",
             "-t", scheme, "-c", cfg],
            check=True, capture_output=True, text=True, cwd=tmp,
        ).stdout
    return json.loads(out)["colors"]


def main():
    seed = sys.argv[1] if len(sys.argv) > 1 else "#5E8C7A"
    scheme = sys.argv[2] if len(sys.argv) > 2 else "scheme-tonal-spot"
    colors = matugen(seed, scheme)

    def role_map(mode):
        return "\n".join(f'        "{camel(r)}": "{colors[r][mode]["color"]}",' for r in ROLES)

    with open(os.path.join(ROOT, "core", "ColorScheme.qml"), "w") as f:
        f.write(f"""// Generated by tools/gen-palette.py — do not edit by hand.
// seed: {seed}  scheme: {scheme}
pragma Singleton
import QtQuick
import Quickshell

// Built-in scheme, used until a wallpaper-derived scheme exists.
Singleton {{
    readonly property string seed: "{seed}"

    readonly property var dark: ({{
{role_map("dark")}
    }})

    readonly property var light: ({{
{role_map("light")}
    }})
}}
""")

    props = "\n".join(
        f'    readonly property color {camel(r)}: roles["{camel(r)}"] ?? fallback["{camel(r)}"]'
        for r in ROLES)
    with open(os.path.join(ROOT, "core", "ThemeColors.qml"), "w") as f:
        f.write(f"""// Generated by tools/gen-palette.py — do not edit by hand.
import QtQuick

// Material 3 colour roles bound to a role map (e.g. a wallpaper-derived
// scheme); any role missing from it comes from `fallback`.
QtObject {{
    property var roles: ({{}})
    property var fallback: ({{}})

{props}
}}
""")


if __name__ == "__main__":
    main()
